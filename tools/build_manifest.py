#!/usr/bin/env python3
"""Resolve every record in the five category files to a Modrinth file.

Reads 0*-*.txt, asks the Modrinth API for a 1.20.1 build of each record and
writes MRPACK-MANIFEST.txt (one section per tier, one line per file) so the
five .mrpack tiers can be built without any CurseForge download.

Usage:  python3 tools/build_manifest.py            (run from the repo root)
"""
import concurrent.futures
import glob
import json
import urllib.parse
import urllib.request

API = "https://api.modrinth.com/v2"
UA = {"User-Agent": "rune-modlist-audit/1.0"}
GAME = '["1.20.1"]'
TIERS = {
    "S": "server mod list (Forge dedicated server)",
    "N": "RUNE no-shaders",
    "L": "RUNE low-end shaders",
    "M": "RUNE mid-tier shaders",
    "H": "RUNE high-end shaders",
}


def get(url):
    req = urllib.request.Request(url, headers=UA)
    return json.load(urllib.request.urlopen(req, timeout=40))


def load_rows():
    rows = []
    for path in sorted(glob.glob("0*-*.txt")):
        with open(path) as fh:
            for line in fh:
                line = line.strip()
                if not line or line.startswith("#"):
                    continue
                parts = line.split("|")
                if len(parts) != 11:
                    raise SystemExit("bad record in %s: %s" % (path, line))
                rows.append(parts)
    return rows


def resolve(row):
    kind, side, src, slug, mr_id, cf_id, cl, sv, ver, packs, name = row
    q = "%s/project/%s/version?game_versions=%s" % (API, mr_id, urllib.parse.quote(GAME))
    versions = get(q)
    if not isinstance(versions, list) or not versions:
        return slug, (None, None, "no 1.20.1 version on Modrinth")
    candidates = versions
    if ver != "n/a":
        pinned = [v for v in candidates if v["version_number"] == ver]
        if not pinned:
            return slug, (None, None, "pinned version %s missing (latest %s)" % (ver, versions[0]["version_number"]))
        candidates = pinned
    if kind == "mod":
        forge = [v for v in candidates if "forge" in v["loaders"]]
        if forge:
            candidates = forge
    if "sildurs" in slug:
        # the "Lite" shader is a separate version entry with the same
        # version_number "2.02" - pick it by file name
        lite = [v for v in candidates if any("Lite" in f["filename"] for f in v["files"])]
        if lite:
            candidates = lite
    version = candidates[0]
    return slug, (version, version["files"][0], None)


def main():
    rows = load_rows()
    with concurrent.futures.ThreadPoolExecutor(4) as pool:
        resolved = dict(pool.map(resolve, rows))

    out = [
        "# =============================================================================",
        "#  RUNE MODPACK  --  MRPACK RESOLUTION MANIFEST",
        "#  Minecraft 1.20.1 / Forge 47.4.10  |  generated by tools/build_manifest.py",
        "#  Generated from the five category files (Modrinth-only): one line per file",
        "#  that must appear in that tier's .mrpack, already resolved through the",
        "#  Modrinth API - no CurseForge download, no manual version hunting.",
        "#",
        "#  Format (pipe separated):",
        "#    kind|side|slug|mr_id|version_id|version_number|file name|size|sha1|url",
        "#",
        "#  A .mrpack \"files\" entry needs path + hashes + downloads[0]. url here is the",
        "#  Modrinth CDN link for that exact file; sha512 lives in the version JSON at",
        "#  https://api.modrinth.com/v2/version/<version_id> if the packer wants it.",
        "#  version_number \"latest\" = the record is version=n/a in the lists (see",
        "#  AUDIT-NOTES D7): the newest 1.20.1 build was taken, pin it for releases.",
        "# =============================================================================",
        "",
    ]
    missing = []
    for tier, desc in TIERS.items():
        selected = sorted((r for r in rows if tier in r[9].split(",")), key=lambda r: r[10].lower())
        out.append("## TIER %s -- %s  (%d files)" % (tier, desc, len(selected)))
        out.append("# kind|side|slug|mr_id|version_id|version_number|file name|size|sha1|url")
        for row in selected:
            kind, side, src, slug, mr_id, cf_id, cl, sv, ver, packs, name = row
            version, file, error = resolved[slug]
            if error:
                missing.append("%s: %s" % (name, error))
                out.append("# UNRESOLVED %s|%s|%s|%s" % (name, slug, mr_id, error))
                continue
            out.append(
                "%s|%s|%s|%s|%s|%s|%s|%d|%s|%s"
                % (
                    kind,
                    side,
                    slug,
                    mr_id,
                    version["id"],
                    "latest" if ver == "n/a" else ver,
                    file["filename"],
                    file["size"],
                    file["hashes"].get("sha1", ""),
                    file["url"],
                )
            )
        out.append("")

    with open("MRPACK-MANIFEST.txt", "w") as fh:
        fh.write("\n".join(out) + "\n")

    print("MRPACK-MANIFEST.txt: %d records, %d tiers" % (len(rows), len(TIERS)))
    if missing:
        print("UNRESOLVED:")
        for line in missing:
            print("  " + line)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
